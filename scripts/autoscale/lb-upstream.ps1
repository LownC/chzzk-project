<#
.SYNOPSIS
    ⑤ 부하 분산기(nginx)가 요청을 보낼 앱 인스턴스 목록을 스케일러가 직접 관리한다. autoscaler.ps1과 cluster-up.ps1이 불러 쓴다.

.DESCRIPTION
    nginx가 Docker DNS로 "app"을 다시 조회하는 방식은 스케일 인으로 내려간 인스턴스를 한동안 목록에 남겨,
    새 요청이 이미 닫힌 인스턴스로만 가다가 502가 날 수 있었다(docs/autoscale.md 3.1 "스케일 인 드레이닝").
    그래서 목록을 파일(deploy/nginx/upstream.d/app-servers.conf, 생성 파일)로 두고 다음 순서를 지킨다.
      - 스케일 아웃: 새 인스턴스가 요청에 답한 뒤에야 목록에 넣는다.
      - 스케일 인: 내릴 인스턴스를 먼저 목록에서 빼고 nginx를 다시 읽게 한 뒤(새 요청이 더는 가지 않음) 잠시 기다렸다가 내린다.
    nginx는 다시 읽어도(reload) 처리 중인 요청과 열린 WebSocket을 끊지 않는다.
#>

# docker는 진행 상황을 stderr로 쓴다. Windows PowerShell 5.1에서 이를 오류로 보지 않도록 종료 코드만 본다.
function Invoke-LbNative([string[]]$arguments) {
    $previous = $ErrorActionPreference
    $ErrorActionPreference = 'Continue'
    try {
        $output = & docker @arguments 2>$null
        $exitCode = $LASTEXITCODE
    } finally {
        $ErrorActionPreference = $previous
    }
    return [pscustomobject]@{ ExitCode = $exitCode; Output = $output }
}

# 실행 중인 앱 컨테이너(ID, 이름, 네트워크 주소, 만든 시각).
function Get-AppInstances([string[]]$Compose) {
    $result = Invoke-LbNative ($Compose + @('ps', '-q', 'app'))
    if ($result.ExitCode -ne 0) { throw "docker compose ps 실패(exit $($result.ExitCode))" }
    foreach ($id in @($result.Output | Where-Object { $_ })) {
        $inspect = Invoke-LbNative @('inspect', '--format', '{{.Name}}|{{.Created}}|{{range .NetworkSettings.Networks}}{{.IPAddress}}{{end}}', $id)
        if ($inspect.ExitCode -ne 0) { continue }
        $name, $created, $ip = "$($inspect.Output)".Trim() -split '\|'
        [pscustomobject]@{ Id = $id; Name = $name.TrimStart('/'); Created = $created; Ip = $ip }
    }
}

# 부하 분산기 컨테이너 안에서(같은 네트워크) 인스턴스에 직접 요청해 답하는지 본다.
function Test-AppReady([string[]]$Compose, [string]$Ip) {
    $result = Invoke-LbNative ($Compose + @('exec', '-T', 'lb', 'wget', '-q', '-O', '/dev/null', '-T', '3', "http://${Ip}:8080/broadcasts"))
    return $result.ExitCode -eq 0
}

function Wait-AppReady([string[]]$Compose, [string]$Ip, [int]$TimeoutSeconds = 180) {
    $deadline = (Get-Date).AddSeconds($TimeoutSeconds)
    while ((Get-Date) -lt $deadline) {
        if (Test-AppReady $Compose $Ip) { return $true }
        Start-Sleep -Seconds 2
    }
    return $false
}

# 목록 파일을 바꾸고, 부하 분산기가 떠 있으면 설정을 검사한 뒤 다시 읽게 한다.
function Set-LbUpstream([string[]]$Compose, [string]$UpstreamFile, [object[]]$Instances, [switch]$NoReload) {
    # nginx가 BOM을 읽지 못하므로 ASCII로 쓴다(주석도 영어).
    $lines = @('# Generated by scripts/autoscale/lb-upstream.ps1. Do not edit.')
    # nginx는 빈 upstream을 받지 않는다. 아직 준비된 인스턴스가 없으면 쓰지 않는 자리 표시만 둔다.
    if (@($Instances).Count -eq 0) { $lines += 'server 127.0.0.1:9 down;' }
    foreach ($instance in @($Instances | Sort-Object Name)) {
        $lines += "server $($instance.Ip):8080 max_fails=1 fail_timeout=5s; # $($instance.Name)"
    }
    New-Item -ItemType Directory -Force (Split-Path $UpstreamFile) | Out-Null
    $temporary = "$UpstreamFile.tmp"
    Set-Content -Path $temporary -Value $lines -Encoding ascii
    Move-Item -Force $temporary $UpstreamFile
    if ($NoReload) { return }

    $test = Invoke-LbNative ($Compose + @('exec', '-T', 'lb', 'nginx', '-t', '-q'))
    if ($test.ExitCode -ne 0) { throw "nginx 설정 검사 실패(exit $($test.ExitCode)). $UpstreamFile을 확인하세요." }
    $reload = Invoke-LbNative ($Compose + @('exec', '-T', 'lb', 'nginx', '-s', 'reload'))
    if ($reload.ExitCode -ne 0) { throw "nginx 다시 읽기 실패(exit $($reload.ExitCode))" }
}
